static const char *const *glyph(char ch) {
  if (ch >= 'a' && ch <= 'z') ch -= 32;
  for (size_t i = 0; i < sizeof GLYPHS / sizeof *GLYPHS; i++)
    if (GLYPHS[i][0][0] == ch) return &GLYPHS[i][1];
  return &GLYPHS[0][1];
}

int font_width(const char *s, int scale) { return (int)strlen(s) * 6 * scale - scale; }

// Draws into an RGBA buffer whose rows run bottom to top (as glReadPixels gives them); x, y from the top left.
// A dark halo keeps the text readable over bright art.
void font_draw(unsigned char *rgba, int w, int h, int x0, int y0, const char *s, int scale,
               unsigned char r, unsigned char g, unsigned char b) {
  for (int pass = 0; pass < 2; pass++) {
    int x = x0;
    for (const char *p = s; *p; p++, x += 6 * scale) {
      const char *const *rows = glyph(*p);
      for (int gy = 0; gy < 7; gy++)
        for (int gx = 0; gx < 5; gx++) {
          if (rows[gy][gx] != '#') continue;
          for (int sy = 0; sy < scale; sy++)
            for (int sx = 0; sx < scale; sx++) {
              const int px = x + gx * scale + sx, py = y0 + gy * scale + sy;
              for (int oy = -1 + pass; oy <= 1 - pass; oy++)   // pass 0: 3x3 halo; pass 1: the pixel itself
                for (int ox = -1 + pass; ox <= 1 - pass; ox++) {
                  const int qx = px + ox, qy = py + oy;
                  if (qx < 0 || qy < 0 || qx >= w || qy >= h) continue;
                  unsigned char *d = rgba + 4 * ((h - 1 - qy) * w + qx);
                  if (pass == 0) { d[0] /= 4; d[1] /= 4; d[2] /= 4; }
                  else { d[0] = r; d[1] = g; d[2] = b; }
                }
            }
        }
    }
  }
}
